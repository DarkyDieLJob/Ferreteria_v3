def leer_todas_las_hojas(filename: str) -> Optional[Tuple[Dict[str, pd.DataFrame], List[str]]]:
    if not os.path.isfile(filename):
        logging.error(f"Archivo no encontrado: {filename}")
        return None
    try:
        if filename.lower().endswith(('.ods')):
            with pd.ExcelFile(filename, engine='odf') as xls:
                sheets = xls.sheet_names
                all_data = pd.read_excel(xls, sheet_name=None, header=None, engine='odf')
        else:
            with pd.ExcelFile(filename) as xls:
                sheets = xls.sheet_names
                all_data = pd.read_excel(xls, sheet_name=None, header=None)

        logging.info(f"Leídas {len(sheets)} hojas del archivo: {filename}")
        return all_data, sheets
    except Exception as e:
        logging.error(f"Error al leer el archivo Excel '{filename}': {e}")
        return None

def modificar_primer_gasto(df: pd.DataFrame, texto_buscar: str, texto_reemplazar: str, max_filas_buscar: int = 40) -> pd.DataFrame:
    df_copy = df.copy()
    try:
        df_subset = df_copy.iloc[:max_filas_buscar]
        coords = np.argwhere(df_subset.values == texto_buscar)
        if coords.size > 0:
            fila, columna = coords[0]
            df_copy.iloc[fila, columna] = texto_reemplazar
    except Exception as e:
        logging.warning(f"Error durante la modificación de '{texto_buscar}': {e}")
    return df_copy

def renombrar_valores_df(df: pd.DataFrame, reemplazos: Dict[str, str]) -> pd.DataFrame:
    df_copy = df.copy()
    try:
        df_copy = df_copy.replace(reemplazos)
    except Exception as e:
        logging.warning(f"Ocurrió un error durante el renombrado de valores: {e}")
    return df_copy

def buscar_valores_adyacentes(df: pd.DataFrame, encabezados: List[str], config: Dict, search_column_index: Optional[int] = None) -> Dict[str, Any]:
    resultados = {enc: None for enc in encabezados}
    logging.debug(f"Iniciando búsqueda adyacente para: {encabezados}")
    logging.debug(f"Buscando en columna específica (si está definida): {search_column_index}")

    config_map = {}
    default_cfg = config.get('default', {'offset': 1, 'nan_a_cero': False})
    logging.debug(f"DEBUG: default_cfg determined as: {default_cfg}")
    for grupo in config.get('grupos', []):
        cfg = default_cfg.copy()
        cfg.update(grupo)
        for nombre in grupo.get('nombres', []):
            config_map[nombre] = cfg

    df_values = df.values

    for encabezado in encabezados:
        try:
            fila = -1
            columna_base = -1

            # Determine search column for current header, prioritize group-specific over global
            current_search_col_idx = config_map.get(encabezado, {}).get('search_column_index', search_column_index)
            logging.debug(f"  Buscando encabezado '{encabezado}'. Columna de búsqueda efectiva: {current_search_col_idx}")

            if current_search_col_idx is not None and 0 <= current_search_col_idx < df_values.shape[1]:
                # Search only in the specified column
                column_slice = df_values[:, current_search_col_idx]
                relative_coords = np.argwhere(column_slice == encabezado)
                if relative_coords.size > 0:
                    fila = relative_coords[0][0]
                    columna_base = current_search_col_idx # The fixed column for search
                    logging.debug(f"Encabezado '{encabezado}' encontrado en ({fila}, {columna_base}) (columna restringida {current_search_col_idx}).")
                else:
                    logging.debug(f"Encabezado '{encabezado}' no encontrado en la columna {current_search_col_idx}.")
                    continue # Move to next header if not found in restricted column
            else:
                # Search entire DataFrame (if no specific column is set or it's out of bounds)
                coords = np.argwhere(df_values == encabezado)
                if coords.size > 0:
                    fila, columna_base = coords[0]
                    logging.debug(f"Encabezado '{encabezado}' encontrado en ({fila}, {columna_base}) (búsqueda completa).")
                else:
                    logging.debug(f"Encabezado '{encabezado}' no encontrado en la hoja.")
                    continue # Move to next header if not found

            # If we reached here, an encabezado was found
            cfg_actual = config_map.get(encabezado, default_cfg)
            logging.debug(f"  DEBUG: cfg_actual for '{encabezado}': {cfg_actual}") # Detailed debug
            offset = cfg_actual.get('offset', 1)
            convertir_nan = cfg_actual.get('nan_a_cero', False)
            logging.debug(f"  Config para '{encabezado}': offset={offset}, nan_a_cero={convertir_nan}")

            columna_valor = columna_base + offset

            if 0 <= columna_valor < df_values.shape[1]:
                valor_celda = df_values[fila, columna_valor]
                logging.debug(f"  Valor crudo en ({fila}, {columna_valor}): {valor_celda}")
                if convertir_nan and pd.isna(valor_celda):
                    resultados[encabezado] = 0
                    logging.debug(f"  Valor es NaN/NaT, convirtiendo a 0.")
                else:
                    resultados[encabezado] = valor_celda
            else:
                logging.warning(f"Columna calculada {columna_valor} (offset {offset}) fuera de límites para '{encabezado}'.")

        except Exception as e:
            logging.error(f"Error procesando el encabezado '{encabezado}': {e}")

        logging.debug(f"  -> Resultado final para '{encabezado}': {resultados[encabezado]}")

    logging.debug("Fin búsqueda adyacente.")
    return resultados

