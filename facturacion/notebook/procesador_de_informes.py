def modificar_primer_gasto(archivo, hoja):
    df = pd.read_excel(archivo, sheet_name=hoja, header=None)
    for fila in range(min(40, len(df))):  # Verificar solo las primeras 40 filas
        for columna in range(len(df.columns)):
            if df.iloc[fila, columna] == 'GASTOS':
                df.iloc[fila, columna] = 'TABLA GASTOS'
                return df  # Detener después de modificar la primera aparición
    return df



# --- FUNCIÓN 1: Renombrar Valores Específicos ---
# Esta función toma un DataFrame y aplica los reemplazos de texto específicos
# que estaban dentro del bucle original.

def renombrar_valores_especificos(df_entrada):
    """
    Busca y reemplaza valores de texto específicos dentro de un DataFrame.

    Args:
        df_entrada (pd.DataFrame): El DataFrame a modificar.

    Returns:
        pd.DataFrame: El DataFrame con los valores reemplazados.
                      Retorna una copia para no modificar el original inesperadamente.
    """
    df = df_entrada.copy() # Trabajar sobre una copia

    # Mapeo de valores a buscar y sus reemplazos
    reemplazos = {
        'TOTAL TARJ. CREDITO': 'TOTAL TARJ. CRED',
        'total dni': 'TOTAL DNI',
        'TOTAL DURACRIL': 'TOTAL DNI', # Nota: también reemplaza a 'TOTAL DNI'
        'TOTAL MASTRO DEBITO': 'TOTAL MASTRO D'
    }

    print("--- Iniciando renombrado específico ---")
    for valor_buscar, valor_reemplazar in reemplazos.items():
        try:
            # np.where devuelve tuplas de arrays (uno por dimensión)
            filas, columnas = np.where(df.values == valor_buscar)

            if len(filas) > 0:
                # Iterar por si aparece más de una vez (aunque el código original solo usaba la primera)
                for fila, columna in zip(filas, columnas):
                     # Verificar si la celda aún contiene el valor original (por si acaso)
                     if df.iloc[fila, columna] == valor_buscar:
                         print(f"  Encontrado '{valor_buscar}' en ({fila}, {columna}). Reemplazando por: '{valor_reemplazar}'")
                         df.iloc[fila, columna] = valor_reemplazar
            # else:
            #     print(f"  Valor '{valor_buscar}' no encontrado.") # Descomentar para depurar

        except Exception as e:
            # Captura errores más específicos si es necesario, pero evita el 'pass' silencioso.
            print(f"  Advertencia: Ocurrió un error buscando/reemplazando '{valor_buscar}': {e}")
            # Considera si deberías detener el proceso o solo registrar el error.
            # Por ahora, continuamos como en el original.
            pass
    print("--- Fin renombrado específico ---")
    return df


# --- FUNCIÓN 2: Buscar Valores Adyacentes a Encabezados ---
# Esta función toma un DataFrame (ya procesado/renombrado) y busca los valores
# asociados a una lista de encabezados, aplicando la lógica de buscar en la
# columna adyacente (+1 o +2 según el caso).

def buscar_valores_finales_parametrizado(df, encabezados_a_buscar, config_desplazamientos, default_config):
    """
    Busca valores en columnas adyacentes a etiquetas específicas en un DataFrame,
    utilizando una configuración parametrizada para el desplazamiento y manejo de NaN.

    Args:
        df (pd.DataFrame): El DataFrame donde buscar.
        encabezados_a_buscar (list): Lista de strings con los encabezados a buscar.
        config_desplazamientos (list): Una lista de diccionarios. Cada diccionario
                                       define un grupo de encabezados y su comportamiento:
                                       {'nombres': ['Lista', 'De', 'Encabezados'],
                                        'offset': int,  # Desplazamiento de columna
                                        'nan_a_cero': bool # Si True, convierte NaN a 0
                                       }
        default_config (dict): Un diccionario con la configuración por defecto
                               a usar si un encabezado no está en ningún grupo:
                               {'offset': int, 'nan_a_cero': bool}

    Returns:
        dict: Diccionario {encabezado: valor_encontrado}.
    """
    resultados_finales = {}
    print(f"\n--- Buscando valores (parametrizado) para: {encabezados_a_buscar} ---")

    for encabezado in encabezados_a_buscar:
        valor_encontrado = None
        try:
            # Buscar la primera ocurrencia del encabezado
            filas, columnas = np.where(df.values == encabezado)

            if len(filas) > 0:
                fila = filas[0]
                columna = columnas[0]
                print(f"  Encabezado '{encabezado}' encontrado en ({fila}, {columna}).")

                # --- Determinar configuración para ESTE encabezado ---
                offset_actual = default_config['offset']
                convertir_nan = default_config['nan_a_cero']
                config_usada = "por defecto"

                for grupo in config_desplazamientos:
                    if encabezado in grupo.get('nombres', []): # Usar .get para seguridad
                        offset_actual = grupo.get('offset', default_config['offset']) # Usar default si falta
                        convertir_nan = grupo.get('nan_a_cero', default_config['nan_a_cero']) # Usar default si falta
                        config_usada = f"grupo {grupo.get('nombres')}"
                        print(f"    Usando configuración específica ({config_usada}): offset={offset_actual}, nan_a_cero={convertir_nan}")
                        break # Encontró config específica, salir del bucle de grupos

                if config_usada == "por defecto":
                     print(f"    Usando configuración por defecto: offset={offset_actual}, nan_a_cero={convertir_nan}")
                # --- Fin determinación de configuración ---

                columna_valor = columna + offset_actual

                # Verificar si la columna calculada existe
                if columna_valor < df.shape[1]:
                    print(f"    Buscando valor en columna {columna_valor} (offset {offset_actual}).")
                    valor_celda = df.iloc[fila, columna_valor]

                    # Aplicar conversión de NaN si corresponde
                    if convertir_nan and pd.isna(valor_celda):
                        print(f"    Valor en ({fila}, {columna_valor}) es NaN/NaT y nan_a_cero=True. Asignando 0.")
                        valor_encontrado = 0
                    else:
                        # Si no es NaN o no hay que convertir, tomar el valor como está
                        valor_encontrado = valor_celda
                else:
                    # La columna calculada no existe
                    print(f"    Advertencia: No existe la columna {columna_valor} (col={columna} + offset={offset_actual}).")
                    valor_encontrado = None # O podrías querer asignar 0 u otro valor

            else:
                # No se encontró el encabezado en el DataFrame
                print(f"  Encabezado '{encabezado}' no encontrado en el DataFrame.")
                valor_encontrado = None # Ya es None por defecto, pero explícito

        except Exception as e:
            print(f"  Error procesando el encabezado '{encabezado}': {e}")
            # Considera logging o un manejo más específico del error
            valor_encontrado = None # Asegurar None en caso de error inesperado

        finally:
            # Guardar el resultado para este encabezado
            resultados_finales[encabezado] = valor_encontrado
            print(f"    -> Resultado para '{encabezado}': {valor_encontrado}")

    print("--- Fin búsqueda de valores (parametrizado) ---")
    return resultados_finales



def buscar_valores(archivo, hojas, encabezados_ods, config_desplazamientos, default_config):
    """
    Función envoltorio que procesa varias hojas de un archivo, aplicando
    modificaciones, renombrados y búsqueda de valores parametrizada.

    Args:
        archivo (str): Ruta al archivo Excel.
        hojas (list): Lista de nombres de hojas a procesar.
        encabezados_ods (list): Lista de encabezados cuyos valores se buscan.
        config_desplazamientos (list): Configuración para buscar_valores_finales_parametrizado.
        default_config (dict): Configuración por defecto para buscar_valores_finales_parametrizado.

    Returns:
        dict: Diccionario con los resultados {nombre_hoja: {encabezado: valor}}.
    """
    resultados = {}
    print(f"\n<<<<<<< Iniciando Proceso General para Archivo: {archivo} >>>>>>>")
    for hoja in hojas:
        print(f"\n======= Procesando Hoja: {hoja} =======")
        try:
            # Paso 1: Modificar primer 'GASTOS' (o simplemente leer si ya no es necesario)
            df_modificado_primer_gasto = modificar_primer_gasto(archivo, hoja)

            # Paso 2: Renombrar valores específicos ('TOTAL TARJ. CREDITO', etc.)
            df_renombrado = renombrar_valores_especificos(df_modificado_primer_gasto)

            # Paso 3: Buscar valores finales usando la configuración parametrizada
            resultados[hoja] = buscar_valores_finales_parametrizado(
                df_renombrado,
                encabezados_ods,
                config_desplazamientos, # Pasar la configuración
                default_config         # Pasar el default
            )
        except FileNotFoundError:
             print(f"  ERROR: Archivo '{archivo}' no encontrado.")
             # Podrías retornar un diccionario vacío o lanzar la excepción
             return {"Error": f"Archivo no encontrado: {archivo}"}
        except Exception as e:
            print(f"  ERROR inesperado procesando la hoja '{hoja}': {e}")
            # Guardar indicación del error para esta hoja
            resultados[hoja] = {"Error": f"Error procesando hoja: {e}"}
            # Considera si quieres continuar con otras hojas o detenerte

    print("\n<<<<<<< Fin Proceso General >>>>>>>")
    return resultados



def buscar_monto_gastos_personales(datos_por_hoja, texto_buscar="Total Gastos Personal=", offset_columnas=5):
    """
    Busca un texto específico en cada DataFrame (hoja) y extrae el valor
    de una celda ubicada a un número determinado de columnas a la derecha.

    Args:
        datos_por_hoja (dict): Diccionario {nombre_hoja: pd.DataFrame}.
        texto_buscar (str): El texto exacto a buscar en las celdas.
        offset_columnas (int): Número de columnas a la derecha para extraer el valor.

    Returns:
        tuple: Una tupla conteniendo:
            - dict: Resultados {nombre_hoja: monto_extraido (float) o None}.
            - float: Suma total de los montos encontrados y válidos.
    """
    resultados_informe = {}
    total_general = 0.0
    print(f"\n<<<<<<< Iniciando Búsqueda de '{texto_buscar}' con offset {offset_columnas} >>>>>>>")

    if not datos_por_hoja:
        print("  ADVERTENCIA: No hay datos por hoja para procesar.")
        return {}, 0.0

    # Iteramos sobre cada hoja (DataFrame) en el diccionario
    for nombre_hoja, df in datos_por_hoja.items():
        print(f"\n======= Procesando Hoja: {nombre_hoja} =======")
        monto_encontrado = None # Reseteamos para cada hoja

        if df.empty:
            print("  INFO: La hoja está vacía. Omitiendo.")
            resultados_informe[nombre_hoja] = None
            continue

        try:
            # Convertimos el DataFrame a un array de NumPy (más rápido para buscar)
            # Usamos dtype=str para asegurar que la comparación funcione aunque haya números
            array_datos = df.to_numpy(dtype=str)

            # Buscamos las coordenadas (fila, columna) donde está el texto
            # np.where devuelve una tupla de arrays (uno para filas, uno para columnas)
            coordenadas = np.where(array_datos == texto_buscar)

            if coordenadas[0].size > 0:
                # Si se encontró el texto (tomamos la primera ocurrencia si hay varias)
                fila_idx = coordenadas[0][0]
                col_idx = coordenadas[1][0]
                print(f"  INFO: Texto '{texto_buscar}' encontrado en fila {fila_idx}, columna {col_idx}.")

                # Calculamos el índice de la columna objetivo
                col_objetivo_idx = col_idx + offset_columnas

                # Verificamos si la columna objetivo está dentro de los límites del DataFrame
                if col_objetivo_idx < array_datos.shape[1]:
                    valor_str = array_datos[fila_idx, col_objetivo_idx]
                    print(f"  INFO: Valor en la celda +{offset_columnas} columnas: '{valor_str}'")

                    # --- INICIO BLOQUE MODIFICADO ---
                    try:
                        # 1. Convertir a string y quitar espacios externos
                        valor_procesar = str(valor_str).strip()

                        if valor_procesar: # Solo procesar si no está vacío
                            # 2. Quitar símbolo de moneda (añadir otros si es necesario)
                            valor_procesar = valor_procesar.replace('$', '')
                            # 3. Quitar separador de miles (asumimos que es '.')
                            valor_procesar = valor_procesar.replace('.', '')
                            # 4. Reemplazar separador decimal (asumimos que es ',') por '.'
                            valor_procesar = valor_procesar.replace(',', '.')
                            # 5. Quitar espacios internos restantes
                            valor_procesar = valor_procesar.replace(' ', '')

                            # 6. Intentar conversión a float (si queda algo después de limpiar)
                            if valor_procesar:
                                valor_numerico = float(valor_procesar)
                                monto_encontrado = valor_numerico
                                total_general += monto_encontrado
                                # Mostrar el valor original para claridad
                                print(f"  ÉXITO: Monto numérico extraído: {valor_numerico} (desde '{valor_str}')")
                            else:
                                print(f"  ADVERTENCIA: El valor original '{valor_str}' quedó vacío después de la limpieza.")
                                monto_encontrado = None # Asegurar que es None si queda vacío
                        else:
                            print(f"  ADVERTENCIA: La celda objetivo ('{valor_str}') está vacía o solo contiene espacios.")
                            monto_encontrado = None # Asegurar que es None si estaba vacío

                    except (ValueError, TypeError) as e:
                        # Informar del error específico y el valor problemático
                        print(f"  ADVERTENCIA: El valor '{valor_str}' (procesado como '{valor_procesar}') no pudo ser convertido a número. Error: {e}. Se omitirá del total.")
                        monto_encontrado = None # Asegurar que es None en caso de error
                    # --- FIN BLOQUE MODIFICADO ---

                else:
                    print(f"  ADVERTENCIA: Se encontró '{texto_buscar}', pero no existen {offset_columnas} columnas a la derecha.")
                    monto_encontrado = None
            else:
                print(f"  INFO: Texto '{texto_buscar}' no encontrado en esta hoja.")

        except Exception as e:
            print(f"  ERROR inesperado procesando la hoja '{nombre_hoja}': {e}")
            # Puedes decidir si quieres que el error pare el proceso o solo lo registre

        # Guardamos el resultado para esta hoja (sea el monto o None)
        resultados_informe[nombre_hoja] = monto_encontrado

    print("\n<<<<<<< Fin Búsqueda >>>>>>>")
    return resultados_informe, total_general
