def update_control_sheet_with_files(control_df: pd.DataFrame, current_year_planillas_path: str) -> pd.DataFrame:
    updated_control_df = control_df.copy()

    if not os.path.exists(current_year_planillas_path):
        logging.warning(f"Ruta de planillas no encontrada: {current_year_planillas_path}")
        return updated_control_df

    try:
        files_in_folder = os.listdir(current_year_planillas_path)
    except Exception as e:
        logging.error(f"Error al listar archivos en '{current_year_planillas_path}': {e}")
        return updated_control_df

    processed_months_from_folder = set()  # To track months for which a valid file was found in the actual folder

    for filename_with_ext in files_in_folder:
        full_path = os.path.join(current_year_planillas_path, filename_with_ext)
        if os.path.isfile(full_path) and \
           filename_with_ext.lower().endswith(('.xlsx', '.xls', '.ods')):

            month = extract_month_from_filename(filename_with_ext)

            if month is not None:
                row_index = updated_control_df[updated_control_df['Mes'] == month].index

                if not row_index.empty:
                    idx = row_index[0]
                    current_status = updated_control_df.loc[idx, 'EstadoProcesamiento']
                    recorded_filename = updated_control_df.loc[idx, 'NombreArchivo']

                    # Use pd.isna for robustness against NaN in recorded_filename
                    if pd.isna(recorded_filename) or str(recorded_filename).lower() == 'none':
                        # Case 1: New file for this month slot
                        logging.info(f"Mes {month}: Nuevo archivo detectado '{filename_with_ext}'. Estado actualizado a '{STATUS_READY_TO_PROCESS}'.")
                        updated_control_df.at[idx, 'NombreArchivo'] = filename_with_ext
                        updated_control_df.at[idx, 'EstadoProcesamiento'] = STATUS_READY_TO_PROCESS
                    elif recorded_filename != filename_with_ext:
                        # Case 2: Filename changed for this month slot
                        logging.info(f"Mes {month}: Archivo ha cambiado de '{recorded_filename}' a '{filename_with_ext}'. Estado actualizado a '{STATUS_READY_TO_PROCESS}'.")
                        updated_control_df.at[idx, 'NombreArchivo'] = filename_with_ext
                        updated_control_df.at[idx, 'EstadoProcesamiento'] = STATUS_READY_TO_PROCESS
                    elif current_status != STATUS_PROCESSED:
                        # Case 3: File found, filename unchanged, but status is not 'Processed'
                        logging.info(f"Mes {month}: Archivo '{filename_with_ext}' encontrado y no procesado ('{current_status}'). Estado actualizado a '{STATUS_READY_TO_PROCESS}'.")
                        updated_control_df.at[idx, 'EstadoProcesamiento'] = STATUS_READY_TO_PROCESS
                    else:
                        # Case 4: File found, filename unchanged, and status is 'Processed'
                        logging.info(f"Mes {month}: Archivo '{filename_with_ext}' ya procesado y sin cambios. Estado '{STATUS_PROCESSED}'.")
                    processed_months_from_folder.add(month)
                else:
                    logging.warning(f"Mes {month} (de archivo '{filename_with_ext}') no encontrado en la hoja de control. Este archivo será ignorado.")
            else:
                logging.warning(f"No se pudo extraer el mes del nombre de archivo '{filename_with_ext}'. Este archivo será ignorado.")
        else:
            logging.debug(f"Omitiendo '{filename_with_ext}': no es un archivo o no es un tipo de Excel/ODS reconocido.")

    # After iterating through all files in the folder, check for months in control_df that didn't have a matching file
    for index, row in updated_control_df.iterrows():
        month_in_control = row['Mes']
        recorded_filename_in_control = row['NombreArchivo']
        status_in_control = row['EstadoProcesamiento']

        if month_in_control not in processed_months_from_folder:
            if pd.isna(recorded_filename_in_control) or str(recorded_filename_in_control).lower() == 'none':
                logging.debug(f"Mes {month_in_control}: No se encontró un archivo en la carpeta para este mes, y no hay un nombre de archivo registrado. Manteniendo estado '{STATUS_UNPROCESSED}'.")
            else:
                # This means a file was previously recorded for this month, but it's no longer in the folder.
                logging.warning(f"Mes {month_in_control}: El archivo registrado '{recorded_filename_in_control}' no se encontró en la carpeta actual. Estableciendo estado a '{STATUS_READY_TO_PROCESS}' para revisión, y borrando el nombre de archivo registrado.")
                updated_control_df.at[index, 'EstadoProcesamiento'] = STATUS_READY_TO_PROCESS  # Mark for attention
                updated_control_df.at[index, 'NombreArchivo'] = None  # Clear the filename as it's missing

    logging.info("Actualización de hoja de control completada.")
    return updated_control_df

