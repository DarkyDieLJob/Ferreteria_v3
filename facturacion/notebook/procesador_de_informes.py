def generar_informe_gastos_con_totales_mensuales(resultados_informe, nombre_archivo="informe_gastos_mensual.xlsx"):
    """
    Genera un archivo Excel con el detalle de gastos por fecha (hoja)
    y añade filas con los totales para cada mes identificado.

    Args:
        resultados_informe (dict): Diccionario {nombre_hoja: monto o None}.
        nombre_archivo (str): Nombre del archivo Excel a generar.
    """
    print(f"\n--- Generando Informe con Totales Mensuales: {nombre_archivo} ---")
    if not resultados_informe:
        print("  ADVERTENCIA: No hay resultados para generar el informe.")
        return # Salir si no hay datos

    # --- 1. Procesar datos originales y calcular totales por mes ---
    datos_para_df_original = []
    totales_por_mes = {} # Diccionario para acumular {mes_numero: total_monto}
    hojas_sin_mes_con_monto = [] # Para registrar hojas no parseables que sí tenían monto

    for nombre_hoja, monto in resultados_informe.items():
        # Siempre añadir la fila original al listado para el DataFrame principal
        datos_para_df_original.append({'Fecha': nombre_hoja, 'Monto': monto})

        # Intentar extraer el mes de la hoja
        mes = get_month_from_sheet_name(nombre_hoja)

        if mes is not None:
            # Si se extrajo un mes válido, intentar sumar el monto
            if monto is not None:
                try:
                    # Asegurarse de que el monto sea numérico antes de sumar
                    monto_float = float(monto)
                    totales_por_mes[mes] = totales_por_mes.get(mes, 0.0) + monto_float
                except (ValueError, TypeError):
                    # Si el monto existe pero no es numérico, registrar advertencia
                    print(f"  ADVERTENCIA: Monto '{monto}' para hoja '{nombre_hoja}' (Mes {mes}) no es numérico, no se incluirá en el total mensual.")
            # else: Si el monto es None, simplemente no se suma a ningún total.
        else:
            # Si no se pudo extraer un mes válido, verificar si había un monto
            if monto is not None:
                # Registrar hoja inválida que sí tenía monto (no se sumará a ningún mes)
                hojas_sin_mes_con_monto.append(nombre_hoja)

    # Informar sobre hojas con montos que no pudieron ser asignadas a un mes
    if hojas_sin_mes_con_monto:
        print(f"  ADVERTENCIA: Las siguientes hojas tienen montos pero no un formato de fecha (d/m) reconocible y sus valores NO se incluirán en los totales mensuales: {hojas_sin_mes_con_monto}")

    # --- 2. Crear DataFrame con los datos originales detallados ---
    df_informe_detalle = pd.DataFrame(datos_para_df_original)
    # Podrías ordenar df_informe_detalle aquí si lo deseas, por ejemplo por 'Fecha'
    # df_informe_detalle = df_informe_detalle.sort_values(by='Fecha') # Orden alfabético simple

    # --- 3. Crear DataFrame para las filas de totales mensuales ---
    datos_para_df_totales = []

