def calcular_columnas_informe(
    df_extraido: pd.DataFrame,
    col_gastos: str,
    venta_final_key: str,
    tarjeta_d_key1: str,
    tarjeta_d_key2: str,
    tarjeta_c_key: str,
    mp_key: str, # NEW PARAMETER
    dni_key: str # NEW PARAMETER
) -> pd.DataFrame:
    df = df_extraido.copy()
    logging.debug(f"DataFrame before numeric conversion in calcular_columnas_informe:\n{df.head()}") # Debug print

    cols_numericas = [
        'Z', 'N', 'DIFERENCIA', venta_final_key, tarjeta_c_key,
        tarjeta_d_key1, tarjeta_d_key2, mp_key, dni_key, # Changed: use mp_key and dni_key
        col_gastos
    ]
    for col in cols_numericas:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors='coerce')

    logging.debug(f"DataFrame after numeric conversion and before fillna(0) for {col_gastos}:\n{df.head()}") # Debug print
    df[col_gastos] = df[col_gastos].fillna(0)
    numeric_cols_to_fill = [
        'Z', 'N', 'DIFERENCIA', venta_final_key, tarjeta_c_key,
        tarjeta_d_key1, tarjeta_d_key2, mp_key, dni_key # Changed: use mp_key and dni_key
    ]
    for col in numeric_cols_to_fill:
         if col in df.columns:
             df[col] = df[col].fillna(0)

    logging.debug(f"DataFrame after all fillna(0):\n{df.head()}") # Debug print

    df['B'] = df.get('Z', 0) # Usar .get con default por si falta la columna
    df['D'] = df.get('DIFERENCIA', 0)
    df['TOTAL DIARIO'] = df.get(venta_final_key, 0)
    df[''] = '' # Columna vacía
    df['Tarjeta D'] = df.get(tarjeta_d_key1, 0) + df.get(tarjeta_d_key2, 0)
    df['Tarjeta C'] = df.get(tarjeta_c_key, 0)
    df['Total MP'] = df.get(mp_key, 0) # Changed: use mp_key
    df['Total DNI'] = df.get(dni_key, 0) # Changed: use dni_key

    logging.debug(f"DataFrame before percentage calculations:\n{df.head()}") # Debug print

    total_diario = df['TOTAL DIARIO']
    divisor_seguro = np.where(total_diario == 0, 1, total_diario) # Evita dividir por 0, resultado será x/1

    df['% Tarjeta D'] = np.divide(df['Tarjeta D'], divisor_seguro, out=np.zeros_like(df['Tarjeta D'], dtype=float), where=divisor_seguro!=0) * 100
    df['% Tarjeta C'] = np.divide(df['Tarjeta C'], divisor_seguro, out=np.zeros_like(df['Tarjeta C'], dtype=float), where=divisor_seguro!=0) * 100
    df['% MP'] = np.divide(df['Total MP'], divisor_seguro, out=np.zeros_like(df['Total MP'], dtype=float), where=divisor_seguro!=0) * 100
    df['% DNI'] = np.divide(df['Total DNI'], divisor_seguro, out=np.zeros_like(df['Total DNI'], dtype=float), where=divisor_seguro!=0) * 100

    return df

def agregar_fila_totales(df: pd.DataFrame, col_dias: str = 'Días') -> pd.DataFrame:
    """Calcula y agrega una fila de totales al DataFrame."""
    logging.info("Agregando fila de totales...")
    if df.empty:
        logging.warning("DataFrame vacío, no se puede agregar fila de totales.")
        return df

    # Seleccionar solo columnas numéricas para sumar, excluyendo la de días si existe
    numeric_cols = df.select_dtypes(include=np.number).columns
    if col_dias in numeric_cols:
        numeric_cols = numeric_cols.drop(col_dias)

    # Calcular suma solo si hay columnas numéricas
    if not numeric_cols.empty:
        suma_columnas = df[numeric_cols].sum()
        # Crear la fila de totales como un DataFrame para concatenar fácilmente
        ultima_fila = pd.DataFrame(suma_columnas).T
        ultima_fila.index = ['TOTALES'] # Nombrar el índice de la fila
    else:
        # Crear una fila vacía con el índice 'TOTALES' si no hay nada que sumar
         ultima_fila = pd.DataFrame(index=['TOTALES'], columns=df.columns)


    # Añadir el conteo de días trabajados
    if col_dias in df.columns and not df.empty:
       # Asegurarse de que la columna 'Días' exista y no esté vacía
       # Tomar el último valor numérico de la columna 'Días'
       dias_validos = pd.to_numeric(df[col_dias], errors='coerce').dropna()
       if not dias_validos.empty:
           ultima_fila[col_dias] = dias_validos.iloc[-1]
       else:
           ultima_fila[col_dias] = 0 # O manejar como prefieras si no hay días válidos
    elif col_dias not in df.columns:
         ultima_fila[col_dias] = len(df) # Alternativa si no hay col Días: contar filas


    # Concatenar la fila de totales
    df_con_totales = pd.concat([df, ultima_fila], ignore_index=False) # Mantener índice original + 'TOTALES'
    logging.info("Fila de totales agregada.")
    return df_con_totales

def procesar_archivo_excel(ruta_archivo: str, ruta_salida: str, config: Dict):
    """
    Orquesta el procesamiento completo de un único archivo Excel.
    """
    logging.info(f"--- Iniciando procesamiento para: {ruta_archivo} ---")

    lectura_result = leer_todas_las_hojas(ruta_archivo)
    if lectura_result is None:
        return # Error ya loggeado en la función de lectura

    datos_por_hoja, hojas_leidas = lectura_result
    resultados_hojas = {}

    for nombre_hoja, df_hoja in datos_por_hoja.items():
        logging.info(f"--- Procesando Hoja: {nombre_hoja} ---")
        # Pass the 'current_file_config' (which is 'config' in this function) directly to procesar_hoja
        resultado_hoja = procesar_hoja(df_hoja, config)
        if resultado_hoja:
            resultados_hojas[nombre_hoja] = resultado_hoja
        else:
            logging.warning(f"No se pudo procesar la hoja: {nombre_hoja}")

    if not resultados_hojas:
        logging.warning(f"No se obtuvieron resultados de ninguna hoja en {ruta_archivo}. No se generará informe.")
        return

    # Convertir resultados a DataFrame
    resultados_df = pd.DataFrame.from_dict(resultados_hojas, orient='index')

    # Filtrar filas cuyo índice (nombre de hoja) contenga '-'
    # Asegurarse de que el índice sea string para la operación .str
    resultados_df.index = resultados_df.index.astype(str)
    resultados_df = resultados_df[resultados_df.index.str.contains('-')]

    if resultados_df.empty:
        logging.warning(f"No quedaron hojas válidas (con '-') tras el filtrado en {ruta_archivo}. No se generará informe.")
        return

    # Calcular columnas derivadas
    df_calculado = calcular_columnas_informe(resultados_df,
                                              col_gastos=TEXTO_GASTOS_ORIGINAL, # Usar constante
                                              venta_final_key=config['venta_final_key'], # Acceder directamente de la config
                                              tarjeta_d_key1=config['tarjeta_d_key1'],
                                              tarjeta_d_key2=config['tarjeta_d_key2'],
                                              tarjeta_c_key=config['tarjeta_c_key'],
                                              mp_key=config['mp_key'], # NEW
                                              dni_key=config['dni_key']) # NEW

    # Agregar columna "Días"
    df_calculado.insert(0, 'Días', range(1, len(df_calculado) + 1))

    # Reordenar y seleccionar columnas finales
    columnas_finales = config.get('columnas_informe_final', df_calculado.columns.tolist())
    # Asegurarse de que solo se incluyan columnas que existen en el df
    columnas_existentes = [col for col in columnas_finales if col in df_calculado.columns]
    df_final = df_calculado[columnas_existentes]


    # Agregar fila de totales
    df_con_totales = agregar_fila_totales(df_final, col_dias='Días')

    # Guardar el informe
    try:
        logging.info(f"Guardando informe final en: {ruta_salida}")
        # Crear directorio si no existe
        os.makedirs(os.path.dirname(ruta_salida), exist_ok=True)
        # Guardar sin el índice del DataFrame en el Excel
        df_con_totales.to_excel(ruta_salida, index=True) # index=True para mantener 'TOTALES' como índice
        logging.info(f"Informe guardado exitosamente.")
    except Exception as e:
        logging.error(f"Error al guardar el archivo Excel '{ruta_salida}': {e}")

    logging.info(f"--- Fin del procesamiento para: {ruta_archivo} ---")

def extract_month_from_filename(filename: str) -> int | None:
    if not isinstance(filename, str) or len(filename) < 2:
        return None
    try:
        month_str = filename[:2]
        month = int(month_str)
        if 1 <= month <= 12:
            return month
        else:
            return None
    except ValueError:
        return None
    except Exception as e:
        return None

