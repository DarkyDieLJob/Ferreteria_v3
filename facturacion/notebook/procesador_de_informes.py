# --- Helper Function para extraer el mes ---
def get_month_from_sheet_name(name):
    """
    Intenta extraer el número de mes (1-12) de un string como 'd/m' o 'dd/mm'.
    Ignora mayúsculas/minúsculas y espacios extra. Retorna None si no es válido.
    """
    if isinstance(name, str) and '/' in name:
        parts = name.split('/')
        if len(parts) == 2:
            try:
                # Limpiar día y mes de espacios y tomar la parte del mes (la segunda)
                day_str, month_str = parts[0].strip(), parts[1].strip()
                if day_str and month_str: # Asegurar que ambas partes no estén vacías
                    month = int(month_str)
                    if 1 <= month <= 12:
                        return month # Retorna el número de mes si es válido
            except ValueError:
                # Ocurre si la parte del mes no es un número entero
                pass
            except Exception:
                # Captura cualquier otro error inesperado durante el parseo
                pass
    # Si no tiene formato d/m, o el mes es inválido, o hubo error
    return None

